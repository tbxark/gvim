#!/usr/bin/env python3
"""Generate commands/commands_gen.go from the Fresh sources.

Usage: python3 commands/gen/generate.py [path/to/refs/fresh]

It reads the builtin command table (crates/fresh-editor/src/input/commands.rs),
the English strings (crates/fresh-editor-core/locales/en.json) and the action
name mapping (crates/fresh-editor/src/input/keybindings.rs), and writes one Go
literal per command. Output is sorted by name in byte order, the order the
legacy palette shows.
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "refs/fresh")
OUT = os.path.join(os.path.dirname(__file__), "..", "commands_gen.go")


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def action_names(src):
    """Map Rust Action variant -> canonical snake_case action string."""
    body = src[src.index("define_action_str_mapping! {"):]
    names = {}
    for m in re.finditer(r'"([a-z0-9_]+)"\s*=>\s*([A-Z][A-Za-z0-9_]*)', body):
        names.setdefault(m.group(2), m.group(1))
    return names


def split_list(text):
    return [item.strip().split("::")[-1] for item in text.split(",") if item.strip()]


def commands(src):
    """Return (name_key, desc_key, variant, contexts, custom_contexts) per CommandDef."""
    out = []
    for block in re.findall(r"CommandDef \{(.*?)\n    \},", src, re.S):
        m = re.search(
            r'name_key:\s*"([^"]+)",\s*desc_key:\s*"([^"]+)",\s*action:\s*\|\|\s*Action::([A-Za-z0-9_]+)',
            block,
        )
        if not m:
            continue
        ctx = re.search(r"contexts:\s*&\[([^\]]*)\]", block)
        cust = re.search(r"custom_contexts:\s*&\[([^\]]*)\]", block)
        out.append((m.group(1), m.group(2), m.group(3),
                    split_list(ctx.group(1)) if ctx else [],
                    split_list(cust.group(1)) if cust else []))
    return out


def go(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    en = json.loads(read("crates/fresh-editor-core/locales/en.json"))
    names = action_names(read("crates/fresh-editor/src/input/keybindings.rs"))
    rows, missing = [], []
    for name_key, desc_key, variant, contexts, custom in commands(read("crates/fresh-editor/src/input/commands.rs")):
        name, desc = en.get(name_key), en.get(desc_key)
        if name is None or desc is None:
            missing.append(name_key)
            continue
        rows.append((name, desc, names.get(variant, ""), contexts, custom, name_key, desc_key))
    rows.sort(key=lambda r: r[0])  # byte order: the legacy palette puts "Below" before "at"
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Code generated by commands/gen/generate.py; DO NOT EDIT.\n\n")
        f.write("package commands\n\n")
        f.write("// builtinCommands is the builtin command table, sorted as the legacy palette sorts it.\n")
        f.write("// Contexts are the Fresh KeyContext names a command is scoped to (empty: any);\n")
        f.write("// CustomContexts are the custom context keys that must be active for it to show.\n")
        f.write("var builtinCommands = []builtinCommand{\n")
        for name, desc, action, contexts, custom, name_key, desc_key in rows:
            extra = ""
            if contexts:
                extra += ", Contexts: []string{%s}" % ", ".join(go(c) for c in contexts)
            if custom:
                extra += ", CustomContexts: []string{%s}" % ", ".join(go(c) for c in custom)
            # Key/DescKey are Fresh's catalogue keys for the English name and
            # description; the palette resolves the title through i18n at display
            # time and keeps Name/Description as the English fallback.
            f.write("\t{Name: %s, Description: %s, Action: %s, Key: %s, DescKey: %s%s},\n"
                    % (go(name), go(desc), go(action), go(name_key), go(desc_key), extra))
        f.write("}\n")
    print("commands:", len(rows), "unresolved:", len(missing),
          "without action:", sum(1 for r in rows if not r[2]))
    if missing:
        print("missing strings:", missing[:10], file=sys.stderr)


if __name__ == "__main__":
    main()