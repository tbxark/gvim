func TestLargeOverCapSelectionsAreRefused(t *testing.T) {
	t.Parallel()
	const width = 1024
	tests := []struct {
		Name   string
		action Action
		Args   map[string]any
		opts   func(*Options)
	}{
		{Name: "copy", action: "copy"},
		{Name: "cut", action: "cut"},
		{Name: "copy with theme", action: "copy_with_theme"},
		{Name: "upper case", action: "to_upper_case"},
		{Name: "lower case", action: "to_lower_case"},
		{Name: "shell filter", action: "shell_command", Args: map[string]any{"command": "cat"}},
		{Name: "shell replace", action: "shell_command_replace", Args: map[string]any{"command": "cat"}},
		{Name: "wrap in brackets", action: "insert_char", Args: map[string]any{"text": "("}, opts: func(o *Options) { o.AutoSurround = true }},
		{Name: "sort", action: "sort_lines"},
	}
	for _, tt := range tests {
		t.Run(tt.Name, func(t *testing.T) {
			t.Parallel()
			src := buffertest.NewVirtual(buffer.MaxMaterialize+4*width, width)
			opts := Options{LargeFileMode: true, LargeFileThresholdBytes: 1024}
			if tt.opts != nil {
				tt.opts(&opts)
			}
			e := New(withSource(opts, src))
			if err := e.OpenFile(writeLargeFile(t, "virtual.txt", strings.Repeat("x", 2048))); err != nil {
				t.Fatal(err)
			}
			d := e.Active()
			indexAll(t, e)
			selectRange(d, buffer.Pos{}, d.Buffer.End())
			e.clipboard = "before"
			version, at := d.Buffer.Version(), d.Cursor
			r := e.Do(tt.action, tt.Args)
			if !errors.Is(r.Err, ErrLargeFile) || !errors.Is(r.Err, buffer.ErrOverCap) {
				t.Fatalf("Do(%s) = %v, want ErrLargeFile and ErrOverCap", tt.action, r.Err)
			}
			if !strings.Contains(r.Err.Error(), "16 MiB") {
				t.Errorf("error %q does not name the limit", r.Err)
			}
			if e.clipboard != "before" || r.Text != "" {
				t.Errorf("clipboard %q, result text %d bytes: must stay as they were", e.clipboard, len(r.Text))
			}
			if d.Buffer.Version() != version || d.Cursor != at || d.Sel == nil {
				t.Errorf("version %d -> %d, caret %v -> %v, selection %v", version, d.Buffer.Version(), at, d.Cursor, d.Sel)
			}
			if got := d.Buffer.Stats().MaterializedBytes; got > 1<<20 {
				t.Errorf("the refusal built %d bytes of text", got)
			}
		})
	}
}

