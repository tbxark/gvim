func TestLargeTypingOverARefusedSelectionTypesNothing(t *testing.T) {
	t.Parallel()
	e, d := openIndexed(t, largeOptions(), withHead("ok line\nbad \xff line\nlast\n"))
	selectRange(d, buffer.Pos{Line: headLines, Col: 1}, buffer.Pos{Line: headLines + 1, Col: 2})
	version := d.Buffer.Version()
	for _, text := range []string{"x", "\n"} {
		action := Action("insert_char")
		if text == "\n" {
			action = "insert_newline"
		}
		r := e.Do(action, map[string]any{"text": text})
		if !errors.Is(r.Err, buffer.ErrInvalidUTF8) {
			t.Fatalf("Do(%s) = %v, want ErrInvalidUTF8", action, r.Err)
		}
		if d.Buffer.Version() != version || d.Buffer.Line(headLines) != "ok line" {
			t.Fatalf("%s: line %q, version %d -> %d: nothing may be typed", action, d.Buffer.Line(headLines), version, d.Buffer.Version())
		}
		if d.Sel == nil || d.Cursor != (buffer.Pos{Line: headLines + 1, Col: 2}) {
			t.Fatalf("%s: selection %v, caret %v: not put back", action, d.Sel, d.Cursor)
		}
	}
}

func TestAutoSaveSkipsLargeDocuments(t *testing.T) {
	t.Parallel()
	opts := largeOptions()
	opts.AutoSaveInterval = time.Second
	opts.EnsureFinalNewline, opts.TrimTrailingWhitespace = true, true
	e, d := openIndexed(t, opts, strings.TrimSuffix(lineText(200), "\n")+"  ")
	typeText(t, e, "x")
	version := d.Buffer.Version()
	if jobs := e.PlanAutoSave(time.Now()); len(jobs) != 0 {
		t.Fatalf("PlanAutoSave planned %d jobs for a large document", len(jobs))
	}
	if err := e.AutoSave(time.Now().Add(time.Hour)); err != nil {
		t.Fatalf("AutoSave = %v", err)
	}
	if d.Buffer.Version() != version || !d.Modified() {
		t.Fatalf("version %d -> %d, modified %v: the auto-save touched the document", version, d.Buffer.Version(), d.Modified())
	}
}

func TestLargeDeletesThatJoinTheNextLineWaitAtTheEndOfTheKnownIndex(t *testing.T) {
	t.Parallel()
	e, d := openLarge(t, largeOptions(), lineText(300))
	last := d.Buffer.Lines() - 1
	if d.Index().Complete || last < 1 {
		t.Fatalf("lines %d, complete %v: want a partial index", last+1, d.Index().Complete)
	}
	end := buffer.Pos{Line: last, Col: d.Buffer.LineLen(last)}
	version := d.Buffer.Version()
	for _, a := range []Action{"delete_forward", "delete_to_line_end", "delete_word_forward"} {
		d.Cursor = end
		if r := e.Do(a, nil); !errors.Is(r.Err, ErrIndexing) {
			t.Errorf("Do(%s) at the end of the last known line = %v, want ErrIndexing", a, r.Err)
		}
	}
	assertUntouched(t, d, version)
	// In the middle of that line the delete does not need the next one.
	d.Cursor = buffer.Pos{Line: last, Col: 2}
	if r := e.Do("delete_forward", nil); r.Err != nil || d.Buffer.Version() == version {
		t.Errorf("delete_forward inside the last known line: %v, changed %v", r.Err, d.Buffer.Version() != version)
	}
}
