// TestLargeSelectionOrWordSaysWhyItRefuses is the regression test for find_selection
// on a large selection saying "No text to search": the selection becomes the search
// text, so a large one is refused with the reason, and nothing is read for it.
func TestLargeSelectionOrWordSaysWhyItRefuses(t *testing.T) {
	t.Parallel()
	const width = 1024
	src := buffertest.NewVirtual(4<<20, width)
	e := New(withSource(Options{LargeFileMode: true, LargeFileThresholdBytes: 1024}, src))
	if err := e.OpenFile(writeLargeFile(t, "virtual.txt", strings.Repeat("x", 2048))); err != nil {
		t.Fatal(err)
	}
	indexAll(t, e)
	d := e.Active()
	tests := []struct {
		Name     string
		From, To buffer.Pos
		refused  bool
	}{
		{"one line", buffer.Pos{Line: 3, Col: 2}, buffer.Pos{Line: 3, Col: 40}, false},
		{"a few lines", buffer.Pos{Line: 3}, buffer.Pos{Line: 6, Col: 5}, false},
		{"just under 64 KiB", buffer.Pos{Line: 10}, buffer.Pos{Line: 10 + 60}, false},
		{"over 64 KiB", buffer.Pos{Line: 10}, buffer.Pos{Line: 10 + 70}, true},
		{"a megabyte", buffer.Pos{Line: 10}, buffer.Pos{Line: 10 + 1000}, true},
		{"the end of one line and the start of the next", buffer.Pos{Line: 3, Col: 1000}, buffer.Pos{Line: 4, Col: 20}, false},
	}
	for _, tc := range tests {
		t.Run(tc.Name, func(t *testing.T) {
			selectRange(d, tc.From, tc.To)
			before := d.Buffer.Stats()
			text, _, _, ok, err := e.SelectionOrWord()
			if tc.refused {
				if ok || text != "" || !errors.Is(err, ErrLargeFile) || !strings.Contains(err.Error(), "64 KiB") {
					t.Fatalf("SelectionOrWord = %d bytes, %v, %v; want a refusal that names 64 KiB", len(text), ok, err)
				}
				if read := d.Buffer.Stats().MaterializedBytes - before.MaterializedBytes; read > 2*width*2 {
					t.Errorf("the refusal read %d bytes of text", read)
				}
				return
			}
			if !ok || err != nil || text == "" {
				t.Fatalf("SelectionOrWord = %d bytes, %v, %v; want the text", len(text), ok, err)
			}
		})
	}
}

