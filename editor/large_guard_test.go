func TestMultiCursorRefusalKeepsTextCaretsRedo(t *testing.T) {
	t.Parallel()
	e, d := openIndexed(t, largeOptions(), withHead("ok line\nbad \xff line\nlast\n"))
	if err := e.GotoLine(headLines+1, 1); err != nil {
		t.Fatal(err)
	}
	typeText(t, e, "q")
	run(t, e, "undo")
	run(t, e, "add_cursor_below")
	if len(d.Cursors()) != 1 {
		t.Fatalf("extra carets = %d, want 1", len(d.Cursors()))
	}
	at, extra, version := d.Cursor, d.Cursors(), d.Buffer.Version()
	r := e.Do("insert_char", map[string]any{"text": "x"})
	if !errors.Is(r.Err, buffer.ErrInvalidUTF8) {
		t.Fatalf("Do = %v, want ErrInvalidUTF8", r.Err)
	}
	if d.Buffer.Version() != version || d.Buffer.Line(headLines) != "ok line" || d.LastMulti != nil {
		t.Errorf("text %q, version %d -> %d, lastMulti %v", d.Buffer.Line(headLines), version, d.Buffer.Version(), d.LastMulti)
	}
	if got := d.Cursors(); d.Cursor != at || len(got) != 1 || got[0].Cursor != extra[0].Cursor {
		t.Errorf("carets %v %v -> %v %v", at, extra, d.Cursor, got)
	}
	// The undone typing can still be redone.
	run(t, e, "redo")
	if got := d.Buffer.Line(headLines); got != "qok line" {
		t.Errorf("line after redo = %q, want the redo stack kept", got)
	}
}

