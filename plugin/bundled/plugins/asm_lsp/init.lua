-- Assembly LSP helper: a port of Fresh's plugins/asm-lsp.ts (328 lines).
--
-- asm-lsp needs a project .asm-lsp.toml to know the assembler dialect and instruction
-- set: without one it assumes GAS syntax on x86/x86-64, so NASM/MASM and ARM/RISC-V
-- files get wrong diagnostics and docs. The plugin offers to create that file when an
-- assembly file opens, guessing the dialect from the language and a bounded sample of
-- the buffer, and it provides the install-help popup for a missing asm-lsp server.
--
-- Fresh's actions that gvim's plugin API has no seam for are not ported: disabling the
-- assembly language server from the popup (gvim exposes no plugin call for it; the native
-- LSP status menu does) and restarting the server for a language (the port runs the
-- native "lsp_restart" action instead, which restarts the active language's servers).
local gvim = require "gvim"

local t = gvim.i18n.t

local ASSEMBLERS = { "gas", "nasm", "masm" }
local COPY_CARGO = "cargo install asm-lsp"
local COPY_BINSTALL = "cargo binstall asm-lsp"

local last_error = nil
local offered = false

local function active_buffer()
  return gvim.buf.current()
end

-- asm_language_for_path maps the file extension to gvim's language key; it does not use
-- the buffer's language field because a plugin's snapshot of a freshly opened buffer can
-- lag behind the open event.
local function asm_language_for_path(path)
  if not path or path == "" then
    return nil
  end
  local lower = string.lower(path)
  if lower:sub(-4) == ".asm" or lower:sub(-5) == ".nasm" then
    return "asm"
  end
  if lower:sub(-2) == ".s" then
    return "gas"
  end
  return nil
end

local function project_root()
  local root = gvim.workspace.root()
  if root and root ~= "" then
    return root
  end
  return gvim.dirs.cwd()
end

local function project_config_path()
  return gvim.path.join(project_root(), ".asm-lsp.toml")
end

-- global_config_exists mirrors asm-lsp's own lookup: XDG_CONFIG_HOME (or ~/.config) and
-- the macOS Application Support directory. It runs through the workspace file system, so
-- in a remote workspace it checks the remote home; the local home cannot be reached from
-- the plugin API (documented residual).
local function global_config_exists()
  local home = gvim.dirs.home()
  if not home or home == "" then
    return false
  end
  local xdg = gvim.env.get("XDG_CONFIG_HOME")
  if xdg and xdg ~= "" then
    if gvim.fs.exists(gvim.path.join(xdg, "asm-lsp", ".asm-lsp.toml")) then
      return true
    end
  elseif gvim.fs.exists(gvim.path.join(home, ".config", "asm-lsp", ".asm-lsp.toml")) then
    return true
  end
  return gvim.fs.exists(gvim.path.join(home, "Library", "Application Support", "asm-lsp", ".asm-lsp.toml"))
end

local function never_key()
  local root = project_root()
  local key = "never:" .. root
  if #key > 200 then
    -- gvim.state keys are capped at 256 bytes; an unusually deep project root keeps a
    -- stable suffix rather than failing to persist the choice.
    key = "never:" .. root:sub(-180)
  end
  return key
end

-- sample_text reads a bounded prefix of the buffer for the dialect/arch sniff.
local function sample_text(buf)
  local lines = buf:lines(0, 16)
  if not lines then
    return ""
  end
  return table.concat(lines, "\n")
end

local function guess_assembler(language, text)
  if language == "gas" then
    return "gas"
  end
  local lower = string.lower(text)
  -- MASM-only tokens and directives: proc/endp/assume/invoke and .model/.code/.data/.stack.
  if lower:find("%f[%w]proc%f[%W]") or lower:find("%f[%w]endp%f[%W]") or
      lower:find("%f[%w]assume%f[%W]") or lower:find("%f[%w]invoke%f[%W]") or
      lower:find("%.model") or lower:find("%.code") or lower:find("%.data") or
      lower:find("%.stack") then
    return "masm"
  end
  return "nasm"
end

local function guess_arch(text)
  local lower = string.lower(text)
  local arm = { "adrp", "stp", "ldp", "xzr", "wzr", "x29", "x30" }
  for _, tok in ipairs(arm) do
    if lower:find("%f[%w]" .. tok .. "%f[%W]") then
      return "arm64"
    end
  end
  local riscv = { "auipc", "jalr", "ecall", "ebreak", "addi", "sltiu" }
  for _, tok in ipairs(riscv) do
    if lower:find("%f[%w]" .. tok .. "%f[%W]") then
      return "riscv"
    end
  end
  return "x86/x86-64"
end

local function config_toml(assembler, arch)
  local lines = {
    "# Generated by gvim (assembly LSP helper).",
    "# Full reference: https://github.com/bergercookie/asm-lsp",
    "[default_config]",
    'assembler = "' .. assembler .. '"',
    'instruction_set = "' .. arch .. '"',
  }
  if assembler ~= "gas" then
    lines[#lines + 1] = ""
    lines[#lines + 1] = "[default_config.opts]"
    lines[#lines + 1] = "# asm-lsp's built-in diagnostics shell out to gcc/clang, which only"
    lines[#lines + 1] = "# assemble GAS syntax - useless for " .. assembler .. ". Turn them off;"
    lines[#lines + 1] = '# point "compiler" at an assembler that understands this dialect to re-enable.'
    lines[#lines + 1] = "default_diagnostics = false"
  end
  lines[#lines + 1] = ""
  return table.concat(lines, "\n")
end

local function create_config(buf, assembler, arch)
  local path = project_config_path()
  local ok, err = gvim.fs.write(path, config_toml(assembler, arch), { atomic = true, mode = 420 })
  if not ok then
    gvim.status(t("status.write_failed", { path = path, error = tostring(err) }))
    return
  end
  gvim.status(t("status.created", { assembler = assembler, arch = arch }))
  -- The server may already be running with its defaults; ask the editor to restart the
  -- active language's servers so the new project config is picked up.
  local ran, run_err = gvim.command.run("lsp_restart")
  if not ran then
    gvim.log.debug("asm_lsp: could not restart the LSP server: %s", tostring(run_err))
  end
end

local function offer_config(buf, force)
  if not buf or not buf:valid() then
    return
  end
  local path = buf:path()
  local language = asm_language_for_path(path)
  if not language then
    return
  end
  if not force and offered then
    return
  end
  if gvim.fs.exists(project_config_path()) or global_config_exists() then
    return
  end
  if gvim.state.get(never_key(), false) then
    return
  end
  offered = true

  local sample = sample_text(buf)
  local assembler = guess_assembler(language, sample)
  local arch = guess_arch(sample)
  local actions = {
    { id = "create:" .. assembler, label = t("offer.create_detected", { assembler = assembler, arch = arch }) },
  }
  for _, alternate in ipairs(ASSEMBLERS) do
    if alternate ~= assembler then
      actions[#actions + 1] = { id = "create:" .. alternate, label = t("offer.create_with", { assembler = alternate, arch = arch }) }
    end
  end
  actions[#actions + 1] = { id = "dismiss", label = t("actions.dismiss") }
  actions[#actions + 1] = { id = "never", label = t("offer.never") }

  local choice = gvim.ui.action_popup({
    title = t("offer.title"),
    message = t("offer.message", { assembler = assembler, arch = arch, path = project_config_path() }),
    actions = actions,
  })
  if not choice or choice == "dismiss" then
    return
  end
  if choice == "never" then
    local ok = gvim.state.set(never_key(), true)
    if ok then
      gvim.status(t("status.never"))
    else
      gvim.status(t("status.never_failed"))
    end
    return
  end
  local chosen = choice:match("^create:(.+)$")
  if not chosen then
    return
  end
  for _, known in ipairs(ASSEMBLERS) do
    if chosen == known then
      create_config(buf, chosen, arch)
      return
    end
  end
end

-- show_help is the install-help popup for a missing/broken asm-lsp server.
local function show_help()
  local buf = active_buffer()
  if not buf or not asm_language_for_path(buf:path()) then
    gvim.status(t("status.not_assembly"))
    return
  end
  local message = t("help.message")
  if last_error then
    message = message .. "\n\n" .. t("help.last_error", { error = last_error })
  end
  local choice = gvim.ui.action_popup({
    title = t("help.title"),
    message = message,
    actions = {
      { id = "copy:cargo", label = t("actions.copy", { value = COPY_CARGO }) },
      { id = "copy:binstall", label = t("actions.copy", { value = COPY_BINSTALL }) },
      { id = "act:lsp_restart", label = t("actions.restart") },
      { id = "act:show_lsp_status", label = t("actions.status") },
      { id = "dismiss", label = t("actions.dismiss") },
    },
  })
  if not choice or choice == "dismiss" then
    return
  end
  local copy = choice:match("^copy:(.+)$")
  if copy == "cargo" then
    gvim.clipboard.set(COPY_CARGO)
    gvim.status(t("status.copied", { value = COPY_CARGO }))
    return
  end
  if copy == "binstall" then
    gvim.clipboard.set(COPY_BINSTALL)
    gvim.status(t("status.copied", { value = COPY_BINSTALL }))
    return
  end
  local action = choice:match("^act:(.+)$")
  if action then
    local ran, err = gvim.command.run(action)
    if not ran then
      gvim.status(t("status.action_failed", { error = tostring(err) }))
    end
  end
end

gvim.command.register({
  name = "create_config",
  title = t("cmd.create_config"),
  description = t("cmd.create_config_desc"),
  run = function()
    local buf = active_buffer()
    if not buf or not asm_language_for_path(buf:path()) then
      gvim.status(t("status.not_assembly"))
      return
    end
    offer_config(buf, true)
  end,
})

gvim.command.register({
  name = "show_help",
  title = t("cmd.show_help"),
  description = t("cmd.show_help_desc"),
  run = function()
    show_help()
  end,
})

gvim.on("after_file_open", function(ev)
  offer_config(gvim.buf.get(ev.buf))
end)

-- Files opened before the plugin finished loading (CLI arguments, session restore) never
-- raise after_file_open for it; sweep the already open buffers once the editor is up.
gvim.on("plugins_loaded", function()
  if offered then
    return
  end
  for _, buf in ipairs(gvim.buf.list()) do
    offer_config(buf)
    if offered then
      return
    end
  end
end)

gvim.on("lsp_server_error", function(ev)
  local buf = active_buffer()
  if not buf or not asm_language_for_path(buf:path()) then
    return
  end
  local message = tostring(ev.error or "")
  -- gvim's payload has no language/server fields; only claim an error that names the
  -- assembly server (a generic error on an asm buffer is not necessarily asm-lsp).
  local lower = string.lower(message)
  if not (lower:find("asm", 1, true) or lower:find("assembly", 1, true)) then
    return
  end
  last_error = message
  if lower:find("not found", 1, true) or lower:find("command not found", 1, true) then
    gvim.status(t("status.server_not_found"))
  else
    gvim.status(t("status.server_error", { error = message }))
  end
end)

gvim.on("lsp_status_clicked", function()
  if not last_error then
    return
  end
  local buf = active_buffer()
  if not buf or not asm_language_for_path(buf:path()) then
    return
  end
  show_help()
end)

gvim.log.debug("asm_lsp: Plugin loaded")
